#!/usr/bin/env python3
"""Turn an official BepInEx 5 (Windows x64) release zip into a Thunderstore "BepInExPack_Spheres" package.

Download BepInEx 5 yourself from https://github.com/BepInEx/BepInEx/releases (for example
BepInEx_win_x64_5.4.23.2.zip; use v5, not v6), then run:

    python Tools/make_bepinex_pack.py path/to/BepInEx_win_x64_5.4.23.2.zip --author YourTeam --out dist

This writes:

    dist/BepInExPack_Spheres/                      the package folder (inspect it before uploading)
        manifest.json
        README.md
        icon.png                                 placeholder cube icon (from package_thunderstore.make_icon)
        BepInExPack/                             everything a mod manager copies into the game/profile root
            winhttp.dll
            doorstop_config.ini                  target -> BepInEx\\core\\BepInEx.Preloader.dll
            BepInEx/core/...
    dist/<Author>-BepInExPack_Spheres-<version>.zip

The BepInExPack/ root folder is the layout used by the BepInExPack packages on Thunderstore; the Spheres entry in
the ecosystem schema has to list this package as its BepInEx loader package with that root folder.

BepInEx is licensed under LGPL-2.1. See docs/RELEASE.md (Legal) for what that means when you redistribute it.
"""
import argparse
import json
import os
import posixpath
import re
import shutil
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from package_thunderstore import make_icon  # noqa: E402

PACK_NAME = "BepInExPack_Spheres"
ROOT = "BepInExPack"
PRELOADER = "BepInEx\\core\\BepInEx.Preloader.dll"
BEPINEX_SOURCE = "https://github.com/BepInEx/BepInEx"

# Written when the release zip has no doorstop_config.ini. It has both the Doorstop 4 section ([General], used by
# BepInEx 5.4.22+) and the Doorstop 3 section ([UnityDoorstop], used by 5.4.21 and older); each version ignores
# the other's section.
DEFAULT_DOORSTOP = """\
# Unity Doorstop config for Spheres (generated by Tools/make_bepinex_pack.py)

# Doorstop 4 (BepInEx 5.4.22 and newer)
[General]
enabled = true
target_assembly = {target}
redirect_output_log = false
boot_config_override =
ignore_disable_switch = false

[UnityMono]
dll_search_path_override =
debug_enabled = false
debug_address = 127.0.0.1:10000
debug_suspend = false

# Doorstop 3 (BepInEx 5.4.21 and older)
[UnityDoorstop]
enabled=true
targetAssembly={target}
redirectOutputLog=false
ignoreDisableSwitch=false
dllSearchPathOverride=
"""

README_TEMPLATE = """\
# BepInExPack for Spheres

[BepInEx]({source}) {bep_version} (Windows x64, Mono) packaged for **Spheres**, so r2modman and other
Thunderstore mod managers can install it. Code mods for Spheres list this package as a dependency.

## Manual install

1. Copy everything inside the `BepInExPack` folder into the folder that contains `Spheres.exe`.
   You should end up with `winhttp.dll`, `doorstop_config.ini` and `BepInEx/` next to the exe.
2. Start the game once. BepInEx creates `BepInEx/plugins` and `BepInEx/config`.
3. Put mods in `BepInEx/plugins/`.

On Linux under Proton/Wine, add `WINEDLLOVERRIDES="winhttp=n,b" %command%` to the game's launch options.

## Contents

This is an unmodified BepInEx release. Only `doorstop_config.ini` was adjusted so its target is
`{target}`.

## License

BepInEx is licensed under the GNU Lesser General Public License v2.1 (LGPL-2.1). Its source code is available
at {source} (release tag matching version {bep_version}). BepInEx bundles other components (HarmonyX, MonoMod,
Mono.Cecil, Unity Doorstop) that have their own licenses; see the BepInEx repository for details.
BepInEx is not made by, or affiliated with, the Spheres developers.
"""


def fail(msg):
    sys.exit("error: " + msg)


def guess_version(zip_path):
    """BepInEx_win_x64_5.4.23.2.zip -> ('5.4.23.2', '5.4.2302'). Thunderstore needs exactly three numbers, so the
    BepInExPack convention packs the 3rd and 4th parts together (5.4.21.0 -> 5.4.2100)."""
    m = re.search(r"(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?", os.path.basename(zip_path))
    if not m:
        return None, None
    major, minor, patch, rev = m.group(1), m.group(2), int(m.group(3)), int(m.group(4) or 0)
    full = "%s.%s.%d.%d" % (major, minor, patch, rev)
    return full, "%s.%s.%d" % (major, minor, patch * 100 + rev)


def safe_rel(name):
    """Return a normalised relative path for a zip entry, or None if it is unsafe (absolute or escaping)."""
    name = name.replace("\\", "/")
    if name.startswith("/") or re.match(r"^[A-Za-z]:", name):
        return None
    norm = posixpath.normpath(name)
    if norm == "." or norm.startswith("../") or norm == "..":
        return None
    return norm


def find_root(names):
    """Find the folder inside the zip that holds winhttp.dll and BepInEx/core (usually the zip root, but a
    re-zipped release may have one wrapping folder)."""
    lower = {n.lower(): n for n in names}
    candidates = []
    for n in names:
        if posixpath.basename(n).lower() == "winhttp.dll":
            candidates.append(posixpath.dirname(n))
    for prefix in sorted(candidates, key=len):
        p = (prefix + "/") if prefix else ""
        if any(k.startswith((p + "bepinex/core/").lower()) for k in lower):
            return prefix
    return None


def patch_doorstop(text, target):
    """Point an existing doorstop_config.ini at the BepInEx preloader and make sure it is enabled."""
    out, found = [], False
    for line in text.splitlines():
        key = line.split("=", 1)[0].strip().lower() if "=" in line and not line.lstrip().startswith(("#", ";")) else ""
        if key in ("target_assembly", "targetassembly"):
            line = "%s = %s" % (line.split("=", 1)[0].strip(), target)
            found = True
        elif key == "enabled":
            line = "%s = true" % line.split("=", 1)[0].strip()
        out.append(line)
    if not found:
        return None
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("bepinex_zip", help="official BepInEx 5 Windows x64 release zip you downloaded")
    ap.add_argument("--author", default="SpheresTeam", help="Thunderstore team that will publish the pack")
    ap.add_argument("--version", help="package version_number (default: derived from the zip name, 5.4.23.2 -> 5.4.2302)")
    ap.add_argument("--out", default="dist", help="output folder (default: dist)")
    ap.add_argument("--website", default=BEPINEX_SOURCE, help="manifest website_url")
    args = ap.parse_args()

    if not os.path.isfile(args.bepinex_zip):
        fail("file not found: " + args.bepinex_zip)
    try:
        src = zipfile.ZipFile(args.bepinex_zip)
    except zipfile.BadZipFile:
        fail(args.bepinex_zip + " is not a zip file")

    bep_version, pack_version = guess_version(args.bepinex_zip)
    if args.version:
        pack_version = args.version
    if not pack_version:
        fail("could not read a version from the zip name; pass --version, e.g. --version 5.4.2302")
    if not re.fullmatch(r"\d+\.\d+\.\d+", pack_version):
        fail("--version must look like 5.4.2302 (three numbers)")
    if bep_version and not bep_version.startswith("5."):
        fail("this looks like BepInEx %s; Spheres needs BepInEx 5" % bep_version)
    bep_version = bep_version or pack_version

    # ---- validate the input zip
    entries = {}
    for info in src.infolist():
        rel = safe_rel(info.filename)
        if rel is None:
            fail("refusing unsafe path in zip: " + info.filename)
        if not info.is_dir():
            entries[rel] = info
    root = find_root(list(entries))
    if root is None:
        fail("zip does not contain winhttp.dll next to a BepInEx/core folder. Download the Windows x64 "
             "BepInEx 5 release (BepInEx_win_x64_5.x.zip), not the Unix, x86 or IL2CPP build.")
    prefix = (root + "/") if root else ""
    payload = {rel[len(prefix):]: info for rel, info in entries.items() if rel.startswith(prefix)}
    if not any(p.lower() == "bepinex/core/bepinex.preloader.dll" for p in payload):
        fail("BepInEx/core/BepInEx.Preloader.dll is missing from the zip")
    if any(p.lower().startswith("bepinex/core/bepinex.unity") or p.lower() == "bepinex/core/bepinex.core.dll"
           for p in payload):
        fail("this looks like BepInEx 6 (BepInEx.Core.dll / BepInEx.Unity.*); Spheres needs BepInEx 5")

    # ---- build the package folder
    pkg_dir = os.path.join(args.out, PACK_NAME)
    if os.path.isdir(pkg_dir):
        shutil.rmtree(pkg_dir)
    pack_root = os.path.join(pkg_dir, ROOT)
    os.makedirs(pack_root)

    doorstop_text = None
    for rel, info in sorted(payload.items()):
        if rel.lower() == "doorstop_config.ini":
            doorstop_text = src.read(info).decode("utf-8", errors="replace")
            continue
        dest = os.path.join(pack_root, *rel.split("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with src.open(info) as fsrc, open(dest, "wb") as fdst:
            shutil.copyfileobj(fsrc, fdst)

    patched = patch_doorstop(doorstop_text, PRELOADER) if doorstop_text else None
    if doorstop_text and patched is None:
        print("warning: doorstop_config.ini in the zip has no target key; writing a fresh one")
    with open(os.path.join(pack_root, "doorstop_config.ini"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(patched or DEFAULT_DOORSTOP.format(target=PRELOADER))

    manifest = {
        "name": PACK_NAME,
        "version_number": pack_version,
        "website_url": args.website,
        "description": "BepInEx %s (Windows x64) for Spheres. Required by Spheres code mods." % bep_version,
        "dependencies": [],
    }
    with open(os.path.join(pkg_dir, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    with open(os.path.join(pkg_dir, "README.md"), "w", encoding="utf-8") as f:
        f.write(README_TEMPLATE.format(source=BEPINEX_SOURCE, bep_version=bep_version, target=PRELOADER))
    make_icon(os.path.join(pkg_dir, "icon.png"), rgb=(120, 200, 120))

    # ---- zip it
    os.makedirs(args.out, exist_ok=True)
    zip_path = os.path.join(args.out, "%s-%s-%s.zip" % (args.author, PACK_NAME, pack_version))
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(pkg_dir):
            for name in sorted(files):
                full = os.path.join(base, name)
                z.write(full, os.path.relpath(full, pkg_dir).replace(os.sep, "/"))

    # ---- validate the output zip
    with zipfile.ZipFile(zip_path) as z:
        names = set(z.namelist())
        required = ["manifest.json", "README.md", "icon.png", ROOT + "/winhttp.dll", ROOT + "/doorstop_config.ini",
                    ROOT + "/BepInEx/core/BepInEx.Preloader.dll"]
        missing = [r for r in required if r not in names]
        if missing:
            fail("output zip is missing: " + ", ".join(missing))
        ini = z.read(ROOT + "/doorstop_config.ini").decode("utf-8")
        if PRELOADER not in ini:
            fail("doorstop_config.ini does not target " + PRELOADER)

    print("BepInEx %s -> %s %s" % (bep_version, PACK_NAME, pack_version))
    print("wrote", pkg_dir)
    print("wrote", zip_path)
    print("Mods should depend on: %s-%s-%s" % (args.author, PACK_NAME, pack_version))


if __name__ == "__main__":
    main()
